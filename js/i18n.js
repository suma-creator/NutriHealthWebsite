/* =========================================================================
   i18n.js — lightweight translation engine.

   HOW IT WORKS:
   - Any element with data-i18n="key" gets its textContent replaced by the
     translation for `key` in the current language (falls back to English,
     then to whatever text was already in the element).
   - Any element with data-i18n-placeholder="key" gets its placeholder
     attribute translated the same way (for inputs).
   - The current language is cached in localStorage (nh_lang) so it applies
     instantly on every page load, before the user's saved profile setting
     has even been fetched from Supabase. auth.js syncs it from
     users.settings.language once that loads, in case they switched
     language on another device.
   - shell.js calls applyTranslations() after it injects the sidebar/topbar,
     and settings.js calls setLang() the moment the language dropdown
     changes, so the whole visible page (including the ones with
     data-i18n attributes) is translated without needing a full reload.

   ADDING A NEW TRANSLATABLE PAGE:
   1. Add data-i18n="some_key" to the element (keep the English text inside
      it as-is — that's the fallback if a key is ever missing).
   2. Add "some_key": "English text" to I18N.en below, and the Bangla
      version to I18N.bn.
   3. That's it — applyTranslations() picks it up automatically.
   ========================================================================= */

